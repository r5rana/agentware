"""agentware_lib.retrieval.scorecard - the derived Markdown scorecard VIEW over the benchmark ledger (layer: retrieval).

Owns: the human-readable trend VIEW regenerated by `bench scorecard` from the
append-only benchmark ledger. The scorecard rel-path constant (SCORECARD_REL =
benchmarks/SCORECARD.md); the trend-table column headers (_SCORECARD_COLS); the
numeric-cell formatter that renders a value or an em-dash when missing/non-numeric
(_fmt_cell); the PURE Markdown renderer over ledger rows - a newest-run-first trend
table plus the latest ablation delta plus the SWE-task section (render_scorecard);
and the read-the-ledger-then-(over)write-SCORECARD.md writer (write_scorecard).

Does NOT own: the append-only benchmark ledger it reads (HISTORY_REL / _read_ledger
-> agentware_lib.retrieval.ledger, referenced via the _ledger module alias by
ATTRIBUTE so the global-resolve gate never walks a foreign sibling function held in
this module's __dict__); the `bench` handlers (cmd_bench / cmd_bench_redact,
now in agentware_lib.retrieval.bench) reach these 5 via the `_scorecard` module
alias by attribute; the ledger-sanitize (_dream_step_bench_redact) + eval/metrics
scorecard regenerators (resident callers) reach these 5 as bare names via the
entrypoint by-name facade; the eval/recall handlers (later seams /
resident).
Layer deps: retrieval -> retrieval (agentware_lib.retrieval.ledger as _ledger,
referenced by ATTRIBUTE). Imports only stdlib os besides that; nothing in
core/knowledge/ops/features imports from here.
Fan-in: 5 (modules that import this; see catalog/modules.json depended_on_by; regen: python3 tests/_manifest_gen.py --write).

INV: render_scorecard is PURE - deterministic given its `rows` (no wall-clock, no
git), so the same ledger always renders the same markdown; write_scorecard reads the
ledger READ-ONLY and (over)writes ONLY the derived SCORECARD.md VIEW - the ledger
stays the immutable system of record.
"""

import os

from agentware_lib.retrieval import ledger as _ledger


SCORECARD_REL = os.path.join("benchmarks", "SCORECARD.md")

_SCORECARD_COLS = ("Run (UTC)", "Commit", "Committed (UTC)", "Strategy", "Mode",
                   "Recall@5", "nDCG@5", "MRR", "p50 ms", "ctx-tok",
                   "Reliability")


def _fmt_cell(value, fmt):
    """Format a numeric ledger cell, or an em-dash when missing/non-numeric."""
    return (fmt % value) if isinstance(value, (int, float)) else "—"


def _trend_table(ordered):
    """Own the headline TREND TABLE: the `_SCORECARD_COLS` header plus one row
    per ledger entry, newest run first. Its own unit because the parent had
    started making a SECOND promise here — the per-run metric CELL CONTRACT
    (which ledger key feeds which column, and the em-dash fallback per cell) —
    which is independent of how the document as a whole is assembled. Returns
    the markdown lines; never empty (the caller guards the no-rows case).
    """
    lines = ["| " + " | ".join(_SCORECARD_COLS) + " |",
             "| " + " | ".join("---" for _ in _SCORECARD_COLS) + " |"]
    for r in ordered:
        m = r.get("metrics", {}) or {}
        cells = [
            r.get("run") or "—",
            "`%s`" % (r.get("commit") or "—"),
            r.get("committed") or "—",
            r.get("strategy") or "—",
            r.get("mode") or "—",
            _fmt_cell(m.get("recall_at_k"), "%.4f"),
            _fmt_cell(m.get("ndcg_at_k"), "%.4f"),
            _fmt_cell(m.get("mrr"), "%.4f"),
            _fmt_cell(m.get("latency_ms_p50"), "%.3f"),
            _fmt_cell(m.get("context_tokens_mean"), "%.1f"),
            _fmt_cell(r.get("reliability"), "%.2f"),
        ]
        lines.append("| " + " | ".join(cells) + " |")
    return lines


def _ablation_section(ordered):
    """Own the LATEST ABLATION DELTA block. Its own unit because the parent had
    started making a THIRD promise here — a SELECTION rule (only the newest row
    carrying an `ablation` payload is shown, and none at all when no row has
    one) layered on a signed-delta format that differs from the trend table's.
    Returns the markdown lines, or [] when no row carries an ablation.
    """
    abl_rows = [r for r in ordered if r.get("ablation")]
    if not abl_rows:
        return []
    a = abl_rows[0]
    abl = a["ablation"]
    delta = abl.get("delta", {}) or {}
    lines = [
        "",
        "## Latest ablation delta (%s vs %s) — commit `%s`, run %s"
        % (abl.get("treatment", "?"), abl.get("baseline", "?"),
           a.get("commit", "?"), a.get("run", "?")),
        "",
        "| Metric | Delta |",
        "| --- | --- |",
    ]
    for label, key in (("Recall@k", "recall_at_k"),
                       ("Precision@k", "precision_at_k"),
                       ("nDCG@k", "ndcg_at_k"), ("MRR", "mrr")):
        v = delta.get(key)
        cell = ("%+.4f" % v) if isinstance(v, (int, float)) else "—"
        lines.append("| %s | %s |" % (label, cell))
    return lines


def _swe_section(ordered):
    """Own the SWE-TASK BENCHMARK section (`suite == 'swe-task'` rows). Its own
    unit because the parent had started making a FOURTH promise here — a second,
    DIFFERENTLY-SHAPED table over a FILTERED subset of the same ledger (seeds /
    per-arm means / signed delta rather than retrieval metrics), whose columns
    owe nothing to `_SCORECARD_COLS`. Returns the markdown lines, or [] when no
    row belongs to the swe-task suite.
    """
    swe_rows = [r for r in ordered if r.get("suite") == "swe-task"]
    if not swe_rows:
        return []
    swe_cols = ("Run (UTC)", "Commit", "Seeds", "Arms", "Delta")
    lines = ["", "## SWE-Task Benchmark", "",
             "| " + " | ".join(swe_cols) + " |",
             "| " + " | ".join("---" for _ in swe_cols) + " |"]
    for r in swe_rows:
        arm_stats = r.get("arms", {})
        arm_summary = "; ".join(
            "%s=%.2f" % (a, s.get("mean", 0))
            for a, s in arm_stats.items())
        d = r.get("delta")
        delta_cell = ("%+.4f" % d) if isinstance(d, (int, float)) else "—"
        cells = [
            r.get("run") or "—",
            "`%s`" % (r.get("commit") or "—"),
            str(r.get("seeds", "—")),
            arm_summary or "—",
            delta_cell,
        ]
        lines.append("| " + " | ".join(cells) + " |")
    return lines


def render_scorecard(rows):
    """Render the append-only ledger rows as a Markdown trend table (newest run
    first) plus the latest ablation delta. Pure: deterministic given `rows`, so
    it is a faithful VIEW over the immutable ledger. Returns the markdown text.
    """
    head = "# agentware Recall / Benchmark Scorecard\n"
    intro = (
        "> Derived VIEW over the append-only benchmark ledger "
        "(`benchmarks/history.jsonl`). Regenerate with "
        "`scripts/agentware bench scorecard`. Newest run first; the ledger "
        "itself is immutable (one row per commit + run-timestamp).\n")
    if not rows:
        return "%s\n%s\n_No benchmark runs recorded yet._\n" % (head, intro)
    ordered = sorted(rows, key=lambda r: r.get("run", ""), reverse=True)
    lines = [head, intro, ""]
    lines.extend(_trend_table(ordered))
    lines.extend(_ablation_section(ordered))
    lines.extend(_swe_section(ordered))
    return "\n".join(lines) + "\n"


def write_scorecard(kdir):
    """Read the ledger and (over)write SCORECARD.md as a derived VIEW. Returns
    (path, row_count). The ledger is read-only here; only the derived markdown
    view is regenerated."""
    rows = _ledger._read_ledger(os.path.join(kdir, _ledger.HISTORY_REL))
    text = render_scorecard(rows)
    path = os.path.join(kdir, SCORECARD_REL)
    parent = os.path.dirname(path)
    if parent:
        os.makedirs(parent, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    return path, len(rows)


